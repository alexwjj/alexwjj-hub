// Run with: ego-browser nodejs < scripts/smoke.mjs
const { default: assert } = await import('node:assert/strict')
const task = await taskSpace('Alex personal hub')
const page = task.page('p1')
await page.cdp('Emulation.clearDeviceMetricsOverride')
const origin = 'http://127.0.0.1:5173/'
const frame = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
const go = async path => {
  await page.goto(`${origin}#${path}`, { waitUntil: 'domcontentloaded' })
  await page.waitForSelector('h1')
}

await go('/')
await page.waitForSelector('.liquid-scene[data-renderer="webgl"]')
assert.equal(await page.evaluate(() => document.querySelectorAll('.liquid-scene').length), 1, 'One shared optical canvas')
await page.click('loc=role:button[name="深色主题"]')
await page.waitForFunction(() => document.documentElement.classList.contains('dark'))
await page.reload()
await page.waitForSelector('h1')
assert(await page.evaluate(() => document.documentElement.classList.contains('dark')), 'Theme survives reload')
await page.click('loc=role:button[name="浅色主题"]')
console.log('PASS: theme persistence')
await page.click('loc=role:tab[name="Codex"]')
await page.click('loc=role:tab[name="Skills"]')
await page.waitForFunction(() => document.querySelector('.manual-tabs [role="tabpanel"]')?.textContent.includes('技能'))
console.log('PASS: manual content')
await page.click('loc=css:.manual-content a')
await page.waitForURL('**/#/tools/codex?tab=skills')
await page.waitForSelector('.entry-list')
assert(await page.evaluate(() => document.querySelector('.entry-list').textContent.includes('Ponytail')), 'Deep link selects Skills')

await page.keyboard.press('ControlOrMeta+k')
await page.fill('loc=role:textbox[name="搜索作品、工具、工作流"]', 'superpowers')
await page.waitForFunction(() => document.querySelectorAll('.search-result').length === 1)
await page.keyboard.press('Enter')
await page.waitForURL('**/#/tools/claude?tab=plugins')
await page.waitForSelector('[role="dialog"]', { state: 'hidden' })
assert(await page.evaluate(() => document.querySelector('.entry-list').textContent.includes('Superpowers')), 'Search opens matching plugin')
await page.keyboard.press('ControlOrMeta+k')
await page.fill('loc=role:textbox[name="搜索作品、工具、工作流"]', 'no-result-47812')
await page.waitForSelector('.search-empty')
await page.keyboard.press('Escape')
await page.waitForSelector('[role="dialog"]', { state: 'hidden' })

console.log('PASS: search')
await go('/projects')
assert.equal(await page.evaluate(() => document.querySelectorAll('.project-card').length) >= 40, true)
await page.click('loc=role:button[name*="开源项目"]')
await page.waitForFunction(() => document.querySelectorAll('.project-card').length > 0 && [...document.querySelectorAll('.project-meta > span')].every(e => e.textContent === '开源项目'))
await page.click('loc=role:button[name*="个人网站"]')
await page.waitForFunction(() => document.querySelectorAll('.project-card').length > 0 && [...document.querySelectorAll('.project-meta > span')].every(e => e.textContent === '个人网站'))
console.log('PASS: project filters')
await go('/tools')
await page.click('loc=role:button[name="设计工具"]')
await page.waitForFunction(() => document.querySelectorAll('.tool-detail-card').length === 1)
assert(await page.evaluate(() => document.querySelector('.tool-detail-card h2').textContent === 'Pencil'))

await go('/')
await page.click('text="展开完整流程"')
await page.waitForSelector('[role="dialog"] .workflow-steps')
assert.equal(await page.evaluate(() => document.querySelectorAll('[role="dialog"] .workflow-steps li').length), 4)
await page.keyboard.press('Escape')
await page.waitForSelector('[role="dialog"]', { state: 'hidden' })

console.log('PASS: tool filters and workflow dialog')
for (const width of [390, 768, 1440]) {
  for (const route of ['/', '/projects', '/workflows', '/tools', '/tools/claude', '/articles', '/about', '/guestbook', '/admin']) {
    await go(route)
    await page.cdp('Emulation.setDeviceMetricsOverride', { width, height: 844, deviceScaleFactor: 1, mobile: width < 760 })
    await frame()
    const dimensions = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }))
    assert(dimensions.content <= dimensions.viewport + 1, `${width}px ${route} overflows: ${JSON.stringify(dimensions)}`)
  }
}

console.log('PASS: responsive routes')
await go('/')
await page.cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true })
await frame()
// Emulation is scoped to this browser call; use DOM events for the mobile layout.
await page.evaluate(() => document.querySelector('[aria-label="打开导航"]').click())
await page.waitForFunction(() => !!document.querySelector('.mobile-nav-dialog [aria-label="移动端导航"]'))
await page.evaluate(() => document.querySelector('.mobile-nav-dialog a[href="#/tools"]').click())
await page.waitForFunction(() => location.hash === '#/tools')
await page.waitForSelector('[role="dialog"]', { state: 'hidden' })
await page.cdp('Emulation.clearDeviceMetricsOverride')
await go('/')
await page.click('loc=role:button[name="深色主题"]')
console.log('PASS: theme persistence, handbook tabs/deep links, search and empty state, filters, workflow dialog, mobile navigation, 27 responsive route checks, shared WebGL layer.')
